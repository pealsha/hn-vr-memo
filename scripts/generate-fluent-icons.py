"""Offline conversion of the five pinned Fluent SVGs to GDI+ vector paths.

Run with Python 3 (standard library only); normal builds do not need Python.
Only absolute M/L/H/V/C/Z commands used by these assets are accepted. Fail on
other SVG features rather than silently generating an inaccurate icon.
"""
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent.parent
ICONS = {
    "Pen": "pen",
    "EraseStroke": "ink_stroke",
    "ErasePart": "eraser",
    "Undo": "arrow_undo",
    "Redo": "arrow_redo",
}
SVG = "{http://www.w3.org/2000/svg}"
output = [
    "// Generated by scripts/generate-fluent-icons.py; do not edit the coordinates.",
    "// Fluent UI System Icons, Copyright (c) 2020 Microsoft Corporation, MIT.",
    "// Source: vendor/fluentui-system-icons/SOURCE.md; full license in THIRD-PARTY-NOTICES.md.",
    "using System.Drawing.Drawing2D;", "", "namespace HandwriteMemo.App;", "",
    "internal static class FluentToolbarIcons", "{",
    "    internal static GraphicsPath Create(ToolbarIcon icon) => icon switch", "    {",
]

for name, asset in ICONS.items():
    source = ET.parse(ROOT / f"vendor/fluentui-system-icons/ic_fluent_{asset}_24_regular.svg").getroot()
    assert source.attrib["viewBox"] == "0 0 24 24"
    assert all(child.tag == SVG + "path" for child in source)
    points, types = [], []
    for element in source:
        assert set(element.attrib) == {"d", "fill"}
        data = element.attrib["d"]
        tokens = re.findall(r"[A-Za-z]|[-+]?(?:\d*\.\d+|\d+\.?\d*)(?:[eE][-+]?\d+)?", data)
        assert not re.sub(r"[\s,]", "", re.sub(r"[A-Za-z]|[-+]?(?:\d*\.\d+|\d+\.?\d*)(?:[eE][-+]?\d+)?", "", data))
        i, command = 0, None
        x = y = "0"
        start = None
        while i < len(tokens):
            if tokens[i].isalpha():
                command = tokens[i]
                i += 1
            assert command in ("M", "L", "H", "V", "C", "Z"), command
            if command == "Z":
                types[-1] |= 128
                x, y = start
                command = None
                continue
            count = {"M": 2, "L": 2, "H": 1, "V": 1, "C": 6}[command]
            values = tokens[i:i + count]
            assert len(values) == count and not any(v.isalpha() for v in values)
            i += count
            if command == "H":
                x = values[0]
            elif command == "V":
                y = values[0]
            else:
                x, y = values[-2:]
            if command == "C":
                points.extend(zip(values[::2], values[1::2]))
                types.extend([3, 3, 3])
            else:
                points.append((x, y))
                types.append(0 if command == "M" else 1)
            if command == "M":
                start = (x, y)
                command = "L"
    output.append(f"        // ic_fluent_{asset}_24_regular.svg (unchanged geometry)")
    output.append(f"        ToolbarIcon.{name} => new(")
    output.append("            [")
    for offset in range(0, len(points), 4):
        output.append("                " + ", ".join(f"new PointF({x}f, {y}f)" for x, y in points[offset:offset + 4]) + ",")
    output.append("            ],")
    output.append("            [" + ", ".join(map(str, types)) + "], FillMode.Winding),")

output.extend(["        _ => throw new ArgumentOutOfRangeException(nameof(icon)),", "    };", "}", ""])
(ROOT / "src/HandwriteMemo.App/Ui/FluentToolbarIcons.Generated.cs").write_text("\n".join(output), encoding="utf-8")
print("Generated five Fluent vector icons from pinned SVGs.")
